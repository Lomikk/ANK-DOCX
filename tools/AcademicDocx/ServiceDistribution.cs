using System.IO.Compression;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;

namespace AcademicDocx;

internal static class ServiceDistribution
{
    public static void Package(string root, string publication)
    {
        root = Path.GetFullPath(root);
        publication = Path.GetFullPath(publication);
        using var configuration = JsonDocument.Parse(File.ReadAllText(Path.Combine(publication, "academic-docx.runtimeconfig.json")));
        if (!configuration.RootElement.GetProperty("runtimeOptions").TryGetProperty("includedFrameworks", out _))
            throw new InvalidDataException("A self-contained publication is required");
        var version = typeof(Program).Assembly.GetName().Version!.ToString(3);
        var name = $"academic-docx-{version}-win-x64.zip";
        var directory = Path.Combine(root, ".tools", "releases");
        Directory.CreateDirectory(directory);
        var archive = Path.Combine(directory, name);
        using (var stream = File.Create(archive))
        using (var zip = new ZipArchive(stream, ZipArchiveMode.Create))
            foreach (var file in Directory.EnumerateFiles(publication, "*", SearchOption.AllDirectories).Order(StringComparer.Ordinal))
            {
                var entry = zip.CreateEntry(Path.GetRelativePath(publication, file).Replace('\\', '/'), CompressionLevel.Optimal);
                entry.LastWriteTime = new DateTimeOffset(2000, 1, 1, 0, 0, 0, TimeSpan.Zero);
                using var input = File.OpenRead(file);
                using var output = entry.Open();
                input.CopyTo(output);
            }
        using var saved = File.OpenRead(archive);
        var sha = Convert.ToHexString(SHA256.HashData(saved));
        var manifest = "@rem Generated by pack-service.cmd; commit this file with the release.\r\n" +
            $"@set \"TASK_SERVICE_VERSION={version}\"\r\n" +
            $"@set \"TASK_SERVICE_URL=https://github.com/Lomikk/ANK-DOCX/releases/download/v{version}/{name}\"\r\n" +
            $"@set \"TASK_SERVICE_SHA256={sha}\"\r\n";
        File.WriteAllText(Path.Combine(root, "tools", "service-release.cmd"), manifest, new UTF8Encoding(false));
        Console.WriteLine("Release archive: " + archive);
        Console.WriteLine("SHA256: " + sha);
    }
}
